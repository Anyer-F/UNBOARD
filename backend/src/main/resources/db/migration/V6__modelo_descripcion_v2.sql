-- ==================== EXPORTACIONES ====================

CREATE TABLE exportacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(30) NOT NULL,
    id_usuario BIGINT,
    id_apadrinado BIGINT,
    id_actividad BIGINT,
    fecha_desde DATE,
    fecha_hasta DATE,
    nombre_archivo VARCHAR(255) NOT NULL,
    clave_almacenamiento VARCHAR(500),
    tipo_mime VARCHAR(100),
    tamanio_bytes BIGINT,
    fecha_generacion TIMESTAMP(6) NOT NULL DEFAULT now(),
    fecha_expiracion TIMESTAMP(6),
    disponible BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT exportacion_tipo_check CHECK (tipo IN (
        'PDF_APADRINADO', 'PDF_ACTIVIDAD', 'ZIP_APADRINADO', 'ZIP_ACTIVIDAD')),
    CONSTRAINT fk_exportacion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id),
    CONSTRAINT fk_exportacion_apadrinado FOREIGN KEY (id_apadrinado)
        REFERENCES apadrinado (id) ON DELETE SET NULL,
    CONSTRAINT fk_exportacion_actividad FOREIGN KEY (id_actividad)
        REFERENCES actividad (id) ON DELETE SET NULL
);

