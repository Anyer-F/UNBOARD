-- V6: modelo de la "Descripción del proyecto v2".
--
-- - Comunidades con modo de incorporación (solicitud o ingreso directo).
-- - Módulos por comunidad (el Módulo 1 se crea automáticamente).
-- - Actividad compartida (Tarea, Anuncio o Material de apoyo) dentro de
--   un módulo, con una ASIGNACIÓN por apadrinado y su propio estado.
-- - Entregas con versiones, sugerencias de mejora y observaciones.
-- - Documentos con origen (coordinador / apadrinado) y entrega.
-- - Exportaciones (PDF / ZIP) registradas.
-- - Historial general (no solo de actividades).
--
-- Los datos existentes se convierten sin pérdida: cada actividad previa
-- (una fila por apadrinado) queda como una actividad con una asignación,
-- y el material de apoyo por comunidad pasa a ser una actividad de tipo
-- MATERIAL_APOYO con sus archivos.

-- ==================== USUARIO: datos personales ====================

ALTER TABLE usuario
    ADD COLUMN telefono VARCHAR(30),
    ADD COLUMN direccion VARCHAR(255),
    ADD COLUMN fecha_nacimiento DATE;

-- ==================== COMUNIDAD ====================

ALTER TABLE comunidad
    ADD COLUMN modo_incorporacion VARCHAR(20) NOT NULL DEFAULT 'SOLICITUD',
    ADD CONSTRAINT comunidad_modo_incorporacion_check
        CHECK (modo_incorporacion IN ('SOLICITUD', 'DIRECTO'));

-- ==================== MÓDULOS ====================

CREATE TABLE modulo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comunidad BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    orden INT NOT NULL DEFAULT 1,
    fecha_creacion TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT fk_modulo_comunidad FOREIGN KEY (id_comunidad)
        REFERENCES comunidad (id) ON DELETE CASCADE
);
CREATE INDEX idx_modulo_comunidad ON modulo (id_comunidad, orden);

-- Módulo 1 universal para cada comunidad existente
INSERT INTO modulo (id_comunidad, nombre, descripcion, orden)
SELECT id, 'Módulo 1', 'Módulo general de la comunidad', 1 FROM comunidad;

-- ==================== ACTIVIDAD (compartida) ====================

ALTER TABLE actividad
    ADD COLUMN tipo VARCHAR(20) NOT NULL DEFAULT 'TAREA',
    ADD COLUMN instrucciones TEXT,
    ADD COLUMN requiere_carta BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN otros_requisitos TEXT,
    ADD COLUMN id_comunidad BIGINT,
    ADD COLUMN id_modulo BIGINT,
    ADD COLUMN asignada_a_comunidad BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN eliminada BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN fecha_eliminacion TIMESTAMP(6),
    ADD COLUMN fecha_actualizacion TIMESTAMP(6),
    ADD COLUMN legacy_material_id BIGINT,
    ADD CONSTRAINT actividad_tipo_check CHECK (tipo IN ('TAREA', 'ANUNCIO', 'MATERIAL_APOYO')),
    ADD CONSTRAINT fk_actividad_comunidad FOREIGN KEY (id_comunidad) REFERENCES comunidad (id),
    ADD CONSTRAINT fk_actividad_modulo FOREIGN KEY (id_modulo) REFERENCES modulo (id);

ALTER TABLE actividad
    ALTER COLUMN fecha_creacion TYPE TIMESTAMP(6) USING fecha_creacion::timestamp;

UPDATE actividad SET requiere_documento = false WHERE requiere_documento IS NULL;
UPDATE actividad SET requiere_fotografia = false WHERE requiere_fotografia IS NULL;
UPDATE actividad SET fecha_creacion = now() WHERE fecha_creacion IS NULL;

-- Comunidad: la del apadrinado o, en su defecto, la principal del coordinador
UPDATE actividad a SET id_comunidad = ap.id_comunidad
FROM apadrinado ap
WHERE a.id_apadrinado = ap.id;

UPDATE actividad a SET id_comunidad = c.id_comunidad
FROM coordinador c
WHERE a.id_comunidad IS NULL AND a.id_coordinador = c.id;

UPDATE actividad a SET id_modulo = m.id
FROM modulo m
WHERE m.id_comunidad = a.id_comunidad AND m.orden = 1;

CREATE INDEX idx_actividad_comunidad ON actividad (id_comunidad, id_modulo);

-- ==================== ASIGNACIÓN ====================

CREATE TABLE asignacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_actividad BIGINT NOT NULL,
    id_apadrinado BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL,
    fecha_asignacion TIMESTAMP(6) NOT NULL DEFAULT now(),
    fecha_inicio TIMESTAMP(6),
    fecha_envio TIMESTAMP(6),
    fecha_aprobacion TIMESTAMP(6),
    fecha_visto TIMESTAMP(6),
    recordatorio_enviado BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT uk_asignacion_actividad_apadrinado UNIQUE (id_actividad, id_apadrinado),
    CONSTRAINT asignacion_estado_check CHECK (estado IN (
        'PENDIENTE', 'EN_PROGRESO', 'ENVIADO', 'EN_REVISION',
        'CORRECCION_SOLICITADA', 'APROBADO', 'VENCIDO', 'PUBLICADO', 'VISTO')),
    CONSTRAINT fk_asignacion_actividad FOREIGN KEY (id_actividad)
        REFERENCES actividad (id) ON DELETE CASCADE,
    CONSTRAINT fk_asignacion_apadrinado FOREIGN KEY (id_apadrinado)
        REFERENCES apadrinado (id) ON DELETE CASCADE
);
CREATE INDEX idx_asignacion_apadrinado ON asignacion (id_apadrinado, estado);

INSERT INTO asignacion (id_actividad, id_apadrinado, estado, fecha_asignacion,
                        fecha_envio, fecha_aprobacion)
SELECT a.id,
       a.id_apadrinado,
       CASE a.estado
           WHEN 'EN_PROCESO' THEN 'EN_PROGRESO'
           WHEN 'ENTREGADA' THEN 'ENVIADO'
           WHEN 'APROBADA' THEN 'APROBADO'
           ELSE a.estado
       END,
       a.fecha_creacion,
       (SELECT max(d.fecha_subida) FROM documento d WHERE d.id_actividad = a.id),
       CASE WHEN a.estado = 'APROBADA' THEN
           COALESCE((SELECT max(h.fecha_hora) FROM historial_actividad h
                     WHERE h.id_actividad = a.id AND h.estado_nuevo = 'APROBADA'), now())
       END
FROM actividad a
WHERE a.id_apadrinado IS NOT NULL;

-- ==================== ENTREGA (con versiones) ====================

CREATE TABLE entrega (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asignacion BIGINT NOT NULL,
    version INT NOT NULL,
    estado VARCHAR(30) NOT NULL,
    comentario TEXT,
    fecha_creacion TIMESTAMP(6) NOT NULL DEFAULT now(),
    fecha_envio TIMESTAMP(6),
    fecha_revision TIMESTAMP(6),
    id_revisor BIGINT,
    CONSTRAINT uk_entrega_version UNIQUE (id_asignacion, version),
    CONSTRAINT entrega_estado_check CHECK (estado IN (
        'BORRADOR', 'ENVIADA', 'EN_REVISION', 'CORRECCION_SOLICITADA', 'APROBADA')),
    CONSTRAINT fk_entrega_asignacion FOREIGN KEY (id_asignacion)
        REFERENCES asignacion (id) ON DELETE CASCADE,
    CONSTRAINT fk_entrega_revisor FOREIGN KEY (id_revisor) REFERENCES usuario (id)
);

-- Entrega v1 para cada asignación que ya tenía archivos o cartas
INSERT INTO entrega (id_asignacion, version, estado, fecha_creacion, fecha_envio)
SELECT s.id, 1,
       CASE s.estado
           WHEN 'ENVIADO' THEN 'ENVIADA'
           WHEN 'EN_REVISION' THEN 'EN_REVISION'
           WHEN 'CORRECCION_SOLICITADA' THEN 'CORRECCION_SOLICITADA'
           WHEN 'APROBADO' THEN 'APROBADA'
           ELSE 'BORRADOR'
       END,
       s.fecha_asignacion,
       CASE WHEN s.estado IN ('ENVIADO', 'EN_REVISION', 'CORRECCION_SOLICITADA', 'APROBADO')
            THEN COALESCE(s.fecha_envio, s.fecha_asignacion) END
FROM asignacion s
WHERE EXISTS (SELECT 1 FROM documento d WHERE d.id_actividad = s.id_actividad)
   OR EXISTS (SELECT 1 FROM carta c WHERE c.id_actividad = s.id_actividad);

-- ==================== SUGERENCIAS Y OBSERVACIONES ====================

CREATE TABLE sugerencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_entrega BIGINT NOT NULL,
    texto TEXT NOT NULL,
    id_usuario BIGINT,
    fecha TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT fk_sugerencia_entrega FOREIGN KEY (id_entrega)
        REFERENCES entrega (id) ON DELETE CASCADE,
    CONSTRAINT fk_sugerencia_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id)
);

-- Las observaciones de correcciones previas pasan a ser sugerencias
INSERT INTO sugerencia (id_entrega, texto, id_usuario, fecha)
SELECT e.id, a.observaciones, c.id_usuario, now()
FROM actividad a
JOIN asignacion s ON s.id_actividad = a.id
JOIN entrega e ON e.id_asignacion = s.id
LEFT JOIN coordinador c ON c.id = a.id_coordinador
WHERE a.estado = 'CORRECCION_SOLICITADA'
  AND a.observaciones IS NOT NULL AND a.observaciones <> '';

CREATE TABLE observacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_expediente BIGINT NOT NULL,
    id_asignacion BIGINT,
    texto TEXT NOT NULL,
    id_usuario BIGINT,
    fecha TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT fk_observacion_expediente FOREIGN KEY (id_expediente)
        REFERENCES expediente (id) ON DELETE CASCADE,
    CONSTRAINT fk_observacion_asignacion FOREIGN KEY (id_asignacion)
        REFERENCES asignacion (id) ON DELETE SET NULL,
    CONSTRAINT fk_observacion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id)
);

-- Las observaciones de aprobaciones previas quedan en el expediente
INSERT INTO observacion (id_expediente, id_asignacion, texto, id_usuario, fecha)
SELECT ex.id, s.id, a.observaciones, c.id_usuario, now()
FROM actividad a
JOIN asignacion s ON s.id_actividad = a.id
JOIN expediente ex ON ex.id_apadrinado = s.id_apadrinado
LEFT JOIN coordinador c ON c.id = a.id_coordinador
WHERE a.estado <> 'CORRECCION_SOLICITADA'
  AND a.observaciones IS NOT NULL AND a.observaciones <> '';

-- ==================== DOCUMENTO ====================

ALTER TABLE documento
    ADD COLUMN origen VARCHAR(20) NOT NULL DEFAULT 'APADRINADO',
    ADD COLUMN id_entrega BIGINT,
    ADD CONSTRAINT documento_origen_check CHECK (origen IN ('COORDINADOR', 'APADRINADO')),
    ADD CONSTRAINT fk_documento_entrega FOREIGN KEY (id_entrega) REFERENCES entrega (id);

-- El material del coordinador no pertenece a un expediente
ALTER TABLE documento ALTER COLUMN id_expediente DROP NOT NULL;

-- Una nueva versión de la entrega reutiliza los archivos de la anterior
ALTER TABLE documento DROP CONSTRAINT IF EXISTS uk_documento_nombre_almacenado;

ALTER TABLE documento DROP CONSTRAINT IF EXISTS documento_tipo_documento_check;
ALTER TABLE documento ADD CONSTRAINT documento_tipo_documento_check CHECK (tipo_documento IN (
    'DOCUMENTO', 'CARTA', 'FOTOGRAFIA', 'FORMULARIO', 'EVIDENCIA', 'MATERIAL', 'OTRO'));

UPDATE documento d SET id_entrega = e.id
FROM asignacion s
JOIN entrega e ON e.id_asignacion = s.id
WHERE s.id_actividad = d.id_actividad;

-- ==================== CARTA ====================

ALTER TABLE carta
    ADD COLUMN id_entrega BIGINT,
    ADD CONSTRAINT fk_carta_entrega FOREIGN KEY (id_entrega) REFERENCES entrega (id);

UPDATE carta c SET id_entrega = e.id
FROM asignacion s
JOIN entrega e ON e.id_asignacion = s.id
WHERE s.id_actividad = c.id_actividad;

-- ==================== MATERIAL DE APOYO → actividades ====================

INSERT INTO actividad (titulo, descripcion, fecha_creacion, requiere_documento,
                       requiere_fotografia, estado, id_coordinador, tipo, id_comunidad,
                       id_modulo, asignada_a_comunidad, legacy_material_id)
SELECT mat.titulo, mat.descripcion, COALESCE(mat.fecha_subida, now()), false, false,
       'PENDIENTE', mat.id_coordinador, 'MATERIAL_APOYO', mat.id_comunidad,
       (SELECT m.id FROM modulo m WHERE m.id_comunidad = mat.id_comunidad AND m.orden = 1),
       true, mat.id
FROM material_apoyo mat;

INSERT INTO documento (descripcion, fecha_subida, nombre_almacenado, nombre_original,
                       ruta_archivo, tamanio_bytes, tipo_documento, tipo_mime,
                       id_actividad, id_usuario, origen)
SELECT mat.descripcion, mat.fecha_subida, mat.nombre_almacenado, mat.nombre_original,
       mat.ruta_archivo, mat.tamanio_bytes, 'MATERIAL', mat.tipo_mime,
       a.id, mat.id_usuario, 'COORDINADOR'
FROM material_apoyo mat
JOIN actividad a ON a.legacy_material_id = mat.id;

INSERT INTO asignacion (id_actividad, id_apadrinado, estado, fecha_asignacion)
SELECT a.id, ap.id, 'PUBLICADO', a.fecha_creacion
FROM actividad a
JOIN apadrinado ap ON ap.id_comunidad = a.id_comunidad
WHERE a.legacy_material_id IS NOT NULL;

DROP TABLE material_apoyo;
ALTER TABLE actividad DROP COLUMN legacy_material_id;

-- ==================== HISTORIAL GENERAL ====================

ALTER TABLE historial_actividad DROP CONSTRAINT IF EXISTS historial_actividad_estado_anterior_check;
ALTER TABLE historial_actividad DROP CONSTRAINT IF EXISTS historial_actividad_estado_nuevo_check;
ALTER TABLE historial_actividad DROP CONSTRAINT IF EXISTS fk_historial_actividad;

ALTER TABLE historial_actividad
    ALTER COLUMN id_actividad DROP NOT NULL,
    ALTER COLUMN estado_nuevo DROP NOT NULL,
    ALTER COLUMN accion TYPE VARCHAR(60),
    ADD COLUMN entidad VARCHAR(30) NOT NULL DEFAULT 'ACTIVIDAD',
    ADD COLUMN id_entidad BIGINT,
    ADD COLUMN referencia VARCHAR(255),
    ADD COLUMN id_asignacion BIGINT,
    ADD COLUMN id_apadrinado BIGINT,
    ADD COLUMN id_comunidad BIGINT,
    ADD CONSTRAINT fk_historial_actividad FOREIGN KEY (id_actividad)
        REFERENCES actividad (id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_historial_asignacion FOREIGN KEY (id_asignacion)
        REFERENCES asignacion (id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_historial_apadrinado FOREIGN KEY (id_apadrinado)
        REFERENCES apadrinado (id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_historial_comunidad FOREIGN KEY (id_comunidad)
        REFERENCES comunidad (id) ON DELETE SET NULL;

UPDATE historial_actividad h
SET id_entidad = h.id_actividad,
    referencia = a.titulo,
    id_asignacion = s.id,
    id_apadrinado = s.id_apadrinado,
    id_comunidad = a.id_comunidad
FROM actividad a
LEFT JOIN asignacion s ON s.id_actividad = a.id
WHERE h.id_actividad = a.id;

UPDATE historial_actividad SET estado_anterior = CASE estado_anterior
    WHEN 'EN_PROCESO' THEN 'EN_PROGRESO' WHEN 'ENTREGADA' THEN 'ENVIADO'
    WHEN 'APROBADA' THEN 'APROBADO' ELSE estado_anterior END,
  estado_nuevo = CASE estado_nuevo
    WHEN 'EN_PROCESO' THEN 'EN_PROGRESO' WHEN 'ENTREGADA' THEN 'ENVIADO'
    WHEN 'APROBADA' THEN 'APROBADO' ELSE estado_nuevo END;

CREATE INDEX idx_historial_apadrinado ON historial_actividad (id_apadrinado, fecha_hora);
CREATE INDEX idx_historial_actividad ON historial_actividad (id_actividad, fecha_hora);

