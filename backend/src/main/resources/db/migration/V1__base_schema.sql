-- V1: Esquema base del sistema UNBOUND (PostgreSQL)
--
-- Tablas core: rol, usuario, comunidad, coordinador, apadrinado,
-- expediente, actividad, historial_actividad, carta, documento, notificacion.
--
-- Las tablas de fases posteriores se crean en sus propias migraciones:
--   codigo_acceso, solicitud_incorporacion -> V2
--   material_apoyo                          -> V3
--   coordinador_comunidad                   -> V5
--
-- El DDL refleja el esquema generado por Hibernate 6.6 (identidad vs.
-- secuencia se conserva tal cual para cada entidad).

-- ==================== ROL ====================
CREATE TABLE rol (
    id BIGINT NOT NULL,
    nombre VARCHAR(255)
);

CREATE SEQUENCE rol_id_seq
    AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE rol_id_seq OWNED BY rol.id;
ALTER TABLE ONLY rol ALTER COLUMN id SET DEFAULT nextval('rol_id_seq'::regclass);
ALTER TABLE ONLY rol ADD CONSTRAINT rol_pkey PRIMARY KEY (id);

-- ==================== USUARIO ====================
CREATE TABLE usuario (
    id BIGINT NOT NULL,
    nombre VARCHAR(100),
    correo VARCHAR(150),
    password VARCHAR(255),
    id_rol BIGINT,
    apellido VARCHAR(100),
    fcm_token VARCHAR(500),
    fcm_token_actualizado TIMESTAMP(6)
);

CREATE SEQUENCE usuario_id_seq
    AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE usuario_id_seq OWNED BY usuario.id;
ALTER TABLE ONLY usuario ALTER COLUMN id SET DEFAULT nextval('usuario_id_seq'::regclass);
ALTER TABLE ONLY usuario ADD CONSTRAINT usuario_pkey PRIMARY KEY (id);
ALTER TABLE ONLY usuario
    ADD CONSTRAINT usuario_id_rol_fkey FOREIGN KEY (id_rol) REFERENCES rol(id);

-- ==================== COMUNIDAD ====================
CREATE TABLE comunidad (
    id BIGINT NOT NULL,
    departamento VARCHAR(150),
    municipio VARCHAR(150),
    nombre VARCHAR(150) NOT NULL
);

ALTER TABLE comunidad ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME comunidad_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);
ALTER TABLE ONLY comunidad ADD CONSTRAINT comunidad_pkey PRIMARY KEY (id);

-- ==================== COORDINADOR ====================
CREATE TABLE coordinador (
    id BIGINT NOT NULL,
    id_usuario BIGINT,
    id_comunidad BIGINT
);

CREATE SEQUENCE coordinador_id_seq
    AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE coordinador_id_seq OWNED BY coordinador.id;
ALTER TABLE ONLY coordinador ALTER COLUMN id SET DEFAULT nextval('coordinador_id_seq'::regclass);
ALTER TABLE ONLY coordinador ADD CONSTRAINT coordinador_pkey PRIMARY KEY (id);
ALTER TABLE ONLY coordinador
    ADD CONSTRAINT coordinador_id_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES usuario(id);
ALTER TABLE ONLY coordinador
    ADD CONSTRAINT coordinador_id_comunidad_fkey FOREIGN KEY (id_comunidad) REFERENCES comunidad(id);

-- ==================== APDINADO ====================
CREATE TABLE apadrinado (
    id BIGINT NOT NULL,
    id_usuario BIGINT,
    id_coordinador BIGINT,
    id_comunidad BIGINT
);

CREATE SEQUENCE apadrinado_id_seq
    AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE apadrinado_id_seq OWNED BY apadrinado.id;
ALTER TABLE ONLY apadrinado ALTER COLUMN id SET DEFAULT nextval('apadrinado_id_seq'::regclass);
ALTER TABLE ONLY apadrinado ADD CONSTRAINT apadrinado_pkey PRIMARY KEY (id);
ALTER TABLE ONLY apadrinado
    ADD CONSTRAINT apadrinado_id_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES usuario(id);
ALTER TABLE ONLY apadrinado
    ADD CONSTRAINT apadrinado_id_coordinador_fkey FOREIGN KEY (id_coordinador) REFERENCES coordinador(id);
ALTER TABLE ONLY apadrinado
    ADD CONSTRAINT apadrinado_id_comunidad_fkey FOREIGN KEY (id_comunidad) REFERENCES comunidad(id);

-- ==================== EXPEDIENTE ====================
CREATE TABLE expediente (
    id BIGINT NOT NULL,
    id_apadrinado BIGINT,
    fecha_creacion DATE,
    codigo VARCHAR(20),
    estado VARCHAR(30) DEFAULT 'ACTIVO'
);

CREATE SEQUENCE expediente_id_seq
    AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE expediente_id_seq OWNED BY expediente.id;
ALTER TABLE ONLY expediente ALTER COLUMN id SET DEFAULT nextval('expediente_id_seq'::regclass);
ALTER TABLE ONLY expediente ADD CONSTRAINT expediente_pkey PRIMARY KEY (id);
ALTER TABLE ONLY expediente
    ADD CONSTRAINT uk_expediente_codigo UNIQUE (codigo);
ALTER TABLE ONLY expediente
    ADD CONSTRAINT expediente_id_apadrinado_fkey FOREIGN KEY (id_apadrinado) REFERENCES apadrinado(id);

-- ==================== ACTIVIDAD ====================
CREATE TABLE actividad (
    id BIGINT NOT NULL,
    descripcion TEXT,
    estado VARCHAR(30) NOT NULL,
    fecha_creacion DATE,
    fecha_limite DATE,
    observaciones TEXT,
    requiere_documento BOOLEAN,
    requiere_fotografia BOOLEAN,
    titulo VARCHAR(150) NOT NULL,
    id_apadrinado BIGINT,
    id_coordinador BIGINT,
    CONSTRAINT actividad_estado_check CHECK (estado IN (
        'PENDIENTE', 'EN_PROCESO', 'ENTREGADA', 'EN_REVISION',
        'APROBADA', 'CORRECCION_SOLICITADA', 'VENCIDO'
    ))
);

ALTER TABLE actividad ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME actividad_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);
ALTER TABLE ONLY actividad ADD CONSTRAINT actividad_pkey PRIMARY KEY (id);
ALTER TABLE ONLY actividad
    ADD CONSTRAINT fk_actividad_coordinador FOREIGN KEY (id_coordinador) REFERENCES coordinador(id);
ALTER TABLE ONLY actividad
    ADD CONSTRAINT fk_actividad_apadrinado FOREIGN KEY (id_apadrinado) REFERENCES apadrinado(id);

-- ==================== HISTORIAL_ACTIVIDAD ====================
CREATE TABLE historial_actividad (
    id BIGINT NOT NULL,
    accion VARCHAR(100) NOT NULL,
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30) NOT NULL,
    fecha_hora TIMESTAMP(6) NOT NULL,
    observaciones TEXT,
    id_actividad BIGINT NOT NULL,
    id_usuario BIGINT,
    CONSTRAINT historial_actividad_estado_anterior_check CHECK (estado_anterior IN (
        'PENDIENTE', 'EN_PROCESO', 'ENTREGADA', 'EN_REVISION',
        'APROBADA', 'CORRECCION_SOLICITADA', 'VENCIDO'
    )),
    CONSTRAINT historial_actividad_estado_nuevo_check CHECK (estado_nuevo IN (
        'PENDIENTE', 'EN_PROCESO', 'ENTREGADA', 'EN_REVISION',
        'APROBADA', 'CORRECCION_SOLICITADA', 'VENCIDO'
    ))
);

ALTER TABLE historial_actividad ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME historial_actividad_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);
ALTER TABLE ONLY historial_actividad ADD CONSTRAINT historial_actividad_pkey PRIMARY KEY (id);
ALTER TABLE ONLY historial_actividad
    ADD CONSTRAINT fk_historial_actividad FOREIGN KEY (id_actividad) REFERENCES actividad(id);
ALTER TABLE ONLY historial_actividad
    ADD CONSTRAINT fk_historial_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id);

-- ==================== CARTA ====================
-- estado: smallint = ordinal de EstadoCarta (0 BORRADOR .. 4 RECHAZADA)
CREATE TABLE carta (
    id BIGINT NOT NULL,
    contenido TEXT NOT NULL,
    estado SMALLINT NOT NULL,
    fecha_creacion TIMESTAMP(6),
    fecha_envio TIMESTAMP(6),
    observaciones TEXT,
    tipo_carta VARCHAR(50) NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    id_actividad BIGINT,
    id_apadrinado BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,
    id_expediente BIGINT NOT NULL,
    CONSTRAINT carta_estado_check CHECK (estado >= 0 AND estado <= 4),
    CONSTRAINT carta_tipo_carta_check CHECK (tipo_carta IN (
        'GENERAL', 'CARTA_PADRINO', 'CARTA_APADRINADO', 'CUMPLEAÑOS',
        'GRACIAS', 'NAVIDAD', 'PERSONAL'
    ))
);

ALTER TABLE carta ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME carta_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);
ALTER TABLE ONLY carta ADD CONSTRAINT carta_pkey PRIMARY KEY (id);
ALTER TABLE ONLY carta
    ADD CONSTRAINT fk_carta_actividad FOREIGN KEY (id_actividad) REFERENCES actividad(id);
ALTER TABLE ONLY carta
    ADD CONSTRAINT fk_carta_apadrinado FOREIGN KEY (id_apadrinado) REFERENCES apadrinado(id);
ALTER TABLE ONLY carta
    ADD CONSTRAINT fk_carta_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id);
ALTER TABLE ONLY carta
    ADD CONSTRAINT fk_carta_expediente FOREIGN KEY (id_expediente) REFERENCES expediente(id);

